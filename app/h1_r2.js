/* h1, круг 2: фандинг-кэрри BTC на резерве (спот BTC + шорт перпа того же номинала, дельта-нейтрально; доход — фандинг BTC fund7; до 2020 данных нет — векселя).
   Доля резерва в кэрри e (остаток — векселя), издержки входа/выхода cost на изменение суммы в кэрри; выключатель по вчерашнему фандингу.
   Для сравнения — только векселя (круг 1). Запуск: node h1_r2.js */
const H = require('./h1_lib.js');
H.head();
H.ev('W + векселя (круг 1)', H.mk(H.yTB(1)));
H.ev('кэрри e 0,9, издержки 0,15%', H.mk(H.carry({ e: 0.9, cost: 0.0015 })), { n100: true });
H.ev('кэрри e 0,5, издержки 0,15%', H.mk(H.carry({ e: 0.5, cost: 0.0015 })));
H.ev('кэрри e 0,9, издержки 0,3%', H.mk(H.carry({ e: 0.9, cost: 0.003 })));
H.ev('кэрри e 0,9, издержки 0,05% (мейкер)', H.mk(H.carry({ e: 0.9, cost: 0.0005 })));
H.ev('кэрри e 0,9, 0,15%, только при fund7 > 0', H.mk(H.carry({ e: 0.9, cost: 0.0015, gate: (X, j) => X.ind.fund7[j] > 0 })));
H.ev('кэрри e 0,9, 0,15%, только fund30 > векселя', H.mk(H.carry({ e: 0.9, cost: 0.0015, gate: (X, j) => X.ind.fund30[j] / 30 / 100 > H.tbd(X, j) })), { n100: true });
H.ev('кэрри e 0,9, 0,15%, без векселей (остаток 0%)', H.mk(H.carry({ e: 0.9, cost: 0.0015, save: 0 })));
H.ev('кэрри с 2024 (фандинг 2024–26, остальное — векселя)', H.mk(H.carry({ e: 0.9, cost: 0.0015, gate: (X, j) => H.year(X.ind.t[j]) >= 2024 })));
// кэрри поверх combo4 без фитилей
H.ev('C + кэрри e 0,9, 0,15%', H.mk(H.carry({ e: 0.9, cost: 0.0015 }), H.polC));
