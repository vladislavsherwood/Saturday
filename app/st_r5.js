/* st, круг 5 — «рисковый шок на фондовом рынке → капитуляция крипты: покупать крупнее».
   Диагностика круга 1: VIX > 40 → +38% за 90 дн (но это 2020-03 и 2025-04), VIX > 30 → +5,5% (без 2022 +21%, после 2021-07 −3,7%),
   покупки combo6 при NDX < 200д и VIX > 25 лучше (+31…+33% против +24%).
   Варианты: (а) копии правил покупки 1–9 с условием шока и долей резерва × m; (б) новое правило первым: шок И страх крипты → взнос + f резерва;
   (в) шок по S&P за неделю. Запуск: node st_r5.js */
const ST = require('./st_lib.js'), { c } = ST;
const go = (nm, S) => ST.ev(nm, S);
const boost = (cond, m) => ST.preMod((r, k) => k <= 8, (r) => ({ act: Math.round((1 + (r.act - 1) * m) * 1e6) / 1e6, conds: [...r.conds, cond] }));
console.log('(а) копии покупок 1–9 при шоке, доля резерва × m');
for (const [nm, cd] of [['VIX > 30', c('st_vix', '>', 30)], ['VIX > 40', c('st_vix', '>', 40)], ['VIX/50д > 1,5', c('st_vixr', '>', 1.5)], ['NDX < 200д', c('st_ndx200', '<', 1)], ['NDX −10% от макс', c('st_ndxdd', '>', 10)]])
  for (const m of [1.5, 2]) go(`покупки ×${m} при ${nm}`, boost(cd, m));
console.log('(б) новое правило первым: шок И страх крипты → взнос + f резерва');
for (const [v, fg, f] of [[30, 25, 0.1], [30, 25, 0.2], [30, 15, 0.2], [35, 25, 0.2], [40, 25, 0.2], [40, 40, 0.2], [30, 40, 0.1]])
  go(`VIX > ${v} И страх < ${fg} → +${f}`, ST.ins([{ act: 1 + f, conds: [c('st_vix', '>', v), c('fng', '<', fg)] }], 0));
console.log('(в) S&P за неделю');
for (const [x, f] of [[-5, 0.1], [-5, 0.2], [-7, 0.2], [-4, 0.1]]) go(`S&P ${x}% за 7 дн → +${f}`, ST.ins([{ act: 1 + f, conds: [c('st_spxr7', '<', x)] }], 0));
for (const [x, f] of [[-5, 0.2], [-7, 0.2]]) go(`S&P ${x}% за 7 дн И страх < 25 → +${f}`, ST.ins([{ act: 1 + f, conds: [c('st_spxr7', '<', x), c('fng', '<', 25)] }], 0));
