/* abl: какие правила combo4 на самом деле мешают — убрать по одному правилу и по семье (копии с множителями сегментов — одна семья).
   Две основы: combo4 и combo4 + ловушка для фитилей (финалист wk: −25/40/60 → 15/25/35%, раз в 3 дня).
   Доход к основе (Σ лог-медиан отбор + экзамен + 50 случ.), по сегментам, строгая; 100 новых — средний лог и лучше/хуже.
   Правило «мешает», если без него доход > 0 и на 100 новых лог > 0. Запуск: node abl_r1.js [fam|one] > scratchpad/abl/r1.log */
const L = require('./r4_lib.js'), { P } = L;
const S0 = { ...L.clone(), rules: require('./found/combo4-best.json').rules.map((r) => JSON.parse(JSON.stringify(r))) }; // настоящая combo4: 57 правил (в r4_lib.S0 нет 57-го — эйфории мемов)
const R = (a, b) => Array.from({ length: b - a + 1 }, (_, i) => a + i);
const FAM = [['1 Капитуляция (страх < 10)', [1]], ['2 Отложенная покупка после выноса OI', [2]], ['3 Волна ликвидаций', [3]], ['4 Паника + сильный страх + сильная паника', [4]],
  ['5 Паника + сильный страх, вынос OI', [5]], ['6 Паника + сильный страх, без выноса', [6]], ['7 Паника, вынос OI, сильная паника', [7]], ['8 Паника, вынос OI', [8]], ['9 Паника без выноса', [9]],
  ['10 Охрана после разворота', [10]], ['11–18 Сильный страх → продать', R(11, 18)], ['19–26 Страх → продать', R(19, 26)], ['27 Разворот BTC', [27]], ['28–30 Перегретый фандинг', R(28, 30)],
  ['31–38 Узкая тихая вершина', R(31, 38)], ['39–50 Широкая тихая вершина', R(39, 50)], ['51 Возврат после вершины', [51]], ['52–54 Памп в медвежьем рынке', R(52, 54)],
  ['55 Альтсезон', [55]], ['56 Эйфория в стейблах', [56]], ['57 Эйфория мемов', [57]], ['4–9 вся паника в стейблах', R(4, 9)]];
const polW = { ...L.pol0, wick: { lv: [[0.25, 0.15], [0.4, 0.25], [0.6, 0.35]], age: 60, every: 3, once: 1, size: 'place' } };
const mode = process.argv[2] || 'fam';
const list = mode === 'fam' ? FAM : R(1, 57).map((i) => [`правило ${i}`, [i]]);
for (const [bn, pol] of [['combo4', L.pol0], ['combo4 + фитили', polW]]) {
  P.setBaseline(S0, pol);
  console.log(`\n=== основа: ${bn} ===`);
  const out = [];
  for (const [nm, ids] of list) {
    const S = L.clone(S0); S.rules = S.rules.filter((_, i) => !ids.includes(i + 1));
    const r = L.run('без ' + nm, S, pol, { quiet: true, n100: true });
    out.push({ nm, inc: r.dseg.all, seg: r.dseg, ok: !r.w, n: r.n100 });
  }
  out.sort((a, b) => b.inc - a.inc);
  const sg = (x) => (x >= 0 ? '+' : '') + x.toFixed(3);
  console.log('без чего'.padEnd(46), 'доход   крупн.  альты   мемы  строгая | 100 новых: лог  лучше/хуже');
  for (const o of out) console.log(`${o.nm.padEnd(46)} ${sg(o.inc)} ${sg(o.seg.big)} ${sg(o.seg.alt)} ${sg(o.seg.meme)}   ${o.ok ? '✔' : '✗'}    | ${sg(o.n.m)}  ${o.n.u}/${o.n.d}${o.inc > 0 && o.n.m > 0 ? '   ← мешает?' : ''}`);
}
