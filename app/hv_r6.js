/* hv, круг 6: паника в стейблах (правила 4–9) у волатильной монеты, которая сама ещё не упала (близко к своему 90-дн. максимуму), — только взнос / половина доли.
   Это P35 агента «мемы» (мем по списку, ddm90 < 35 → паника взносом; держался только на 2025–26), но по признаку волатильности. Проверка по периодам: правило только до / только с 2025-01-01. */
const H = require('./hv_lib.js'), { c } = H;
const PAN = (r, k) => k >= 3 && k <= 8;
const NB = [c('isbig', '<', 0.5)];
const mod = (T, f, ex = []) => (r) => { r.conds.push(...H.HV(T), ...NB, ...ex); r.act = f(r.act); return r; };
const one = () => 1, half = (a) => 1 + (a - 1) / 2;
H.head();
H.ev('combo5', H.S5);
for (const D of [25, 35, 50]) for (const [fn, f] of [['взнос', one], ['половина', half]]) H.ev(`T115 ddm90<${D} паника → ${fn}`, H.preMod(H.S5, PAN, mod(115, f, [c('ddm90', '<', D)])));
for (const T of [100, 130]) H.ev(`T${T} ddm90<35 паника → взнос`, H.preMod(H.S5, PAN, mod(T, one, [c('ddm90', '<', 35)])));
const t25 = H.T('2025-01-01');
H.ev('T115 ddm90<35 → взнос, только до 2025', H.preMod(H.S5, PAN, mod(115, one, [c('ddm90', '<', 35), c('t', '<', t25)])));
H.ev('T115 ddm90<35 → взнос, только с 2025', H.preMod(H.S5, PAN, mod(115, one, [c('ddm90', '<', 35), c('t', '>', t25 - 0.5)])));
