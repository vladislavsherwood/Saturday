/* r4, круг 3: мемы в «эйфории» на точных ценах Binance.
   Гипотеза: исключение мемов из эйфории — артефакт округлённых цен Yahoo (провал PEPE был −5 п. п., на Binance −0,7 п. п.). Правило без условия «не мем»
   (проще на одно условие) при доле ≥ 6% проходит строгую и держит плато по доле/порогу; либо у мемов своя доля (правило-копия).
   Критерий (заранее): строгая ✔ везде, доход > 0, ≥ 2/3 соседей ✔ и в плюсе; 100 новых: средний лог ≥ 0, монет/половин в плюсе не меньше.
   Запуск: node r4_r3.js */
const L = require('./r4_lib.js'), { S0, c } = L;
const noE = () => { const S = L.clone(); S.rules.pop(); return S; };
// общая доля, мемы включены (условие «не мем» убрано)
const all = (s, u = 0.9, b = 0.9, A = 540) => { const S = noE(); S.rules.push({ act: -s, conds: [c('usdt', '<', u), c('age', '>', A), c('beta180', '>', b)] }); return S; };
// раздельно: не мемы — как в combo4 (5%), мемы — своя доля sm
const split = (sm, u = 0.9, b = 0.9, A = 540) => { const S = L.clone(); S.rules.push({ act: -sm, conds: [c('usdt', '<', u), c('age', '>', A), c('meme', '>', 0.5), c('beta180', '>', b)] }); return S; };
console.log('— общая доля для всех, мемы включены —');
const R = {};
for (const s of [0.05, 0.06, 0.07, 0.08, 0.1, 0.12, 0.15]) R['a' + s] = L.run(`все, доля ${s * 100}%`, all(s));
console.log('— мемам своя доля (остальным 5%, как в combo4) —');
for (const s of [0.03, 0.05, 0.08, 0.1, 0.15, 0.2, 0.3]) R['s' + s] = L.run(`мемы ${s * 100}%`, split(s));
console.log('— соседи лучших —');
for (const [u, b, A] of [[0.88, 0.9, 540], [0.92, 0.9, 540], [0.85, 0.9, 540], [0.9, 1.0, 540], [0.9, 1.2, 540], [0.9, 0.9, 365], [0.9, 0.9, 730]]) { L.run(`все 8%: usdt ${u} бета ${b} A ${A}`, all(0.08, u, b, A)); L.run(`мемы 10%: usdt ${u} бета ${b} A ${A}`, split(0.1, u, b, A)); }
module.exports = { all, split, noE };
