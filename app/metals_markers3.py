"""Складываются ли маркеры металлов: сколько маркеров вершины (дна) выполнено в день, когда металл на 90-дневном
максимуме (минимуме), и что стало с ценой через полгода — по группам металлов и по периодам.

Запуск: python3 app/metals_markers3.py <metals_markers.pkl>
"""
import sys

import pandas as pd

TOP = [("Золото к серебру: соотношение против средней за 200 дней", "<", 0.941), ("Платина к золоту: соотношение против средней за 200 дней", ">", 1.02),
       ("Инфляция: изменение за полгода, п.п.", ">", 0.388), ("Нефть: изменение за год, %", ">", 19.7), ("Реальная доходность 10 лет (TIPS), %", "<", 0.65),
       ("Безработица: изменение за полгода, п.п.", "<", -0.2), ("Отклонение ставки от нейтральной, п.п.", "<", -2.83)]
BOT = [("Нефть: цена к средней за 200 дней", "<", 0.89), ("Медь к золоту: соотношение против средней за 200 дней", "<", 0.915),
       ("Платина к золоту: соотношение против средней за 200 дней", "<", 0.914), ("Акции: изменение за год, %", "<", 0.361),
       ("Золото к нефти: соотношение против средней за 200 дней", ">", 1.09), ("Акции: до исторического максимума, %", ">", 18.3)]


def count(D, marks):
    return sum(((D[f] > v) if op == ">" else (D[f] < v)).astype(int) for f, op, v in marks)


def table(D, marks, lab, good):
    n = count(D, marks)
    print(f"{'маркеров':>9} {'дней':>6} {'металлов':>9} {'в зоне, %':>10} {'через полгода':>14} {'удача, %':>9} {'через год':>10}")
    for lo, hi, name in ((0, 0, "0"), (1, 1, "1"), (2, 2, "2"), (3, 3, "3"), (4, 9, "4+")):
        g = D[(n >= lo) & (n <= hi)]
        if len(g) < 30:
            continue
        print(f"{name:>9} {len(g):>6} {g.coin.nunique():>9} {g[lab].mean() * 100:>10.0f} {g['_f126'].median():>13.0f}% {(g['_f126'] * good > 0).mean() * 100:>9.0f} {g['_f252'].median():>9.0f}%")


def main(pkl):
    A = pd.read_pickle(pkl)
    for cond, marks, lab, good, title in (("_hi90", TOP, "top", -1, "ВЕРШИНЫ: металл на 90-дневном максимуме"), ("_lo90", BOT, "bot", 1, "ДНО: металл на 90-дневном минимуме")):
        D = A[A[cond].fillna(False).astype(bool) & A["_f126"].notna()]
        print(f"\n=== {title} ===\nмаркеры: " + "; ".join(f"{f} {op} {v}" for f, op, v in marks))
        for name, m in (("все металлы и годы", D.index == D.index), ("золото, серебро, медь", D.grp == "A"), ("платина, палладий", D.grp == "B"), ("до 2013", D.index < "2013-01-01"), ("с 2013", D.index >= "2013-01-01")):
            print(f"-- {name}")
            table(D[m], marks, lab, good)
        for metal in D.coin.unique():
            g = D[D.coin == metal]
            n = count(g, marks)
            hot, cold = g[n >= 4], g[n <= 1]
            print(f"   {metal}: при 4+ маркерах через полгода {hot['_f126'].median():.0f}% ({len(hot)} дн.), при 0–1 маркере {cold['_f126'].median():.0f}% ({len(cold)} дн.)")
        n = count(D, marks)
        months = sorted(set(D[n >= 4].index.strftime("%Y-%m")))
        years = sorted({m[:4] for m in months})
        print(f"месяцев с 4+ маркерами: {len(months)}, годы: {', '.join(years)}")
    # сегодня
    last = A[A.index == A.index.max()]
    print("\nпоследний размеченный день:", A.index.max().date())


if __name__ == "__main__":
    main(sys.argv[1])
