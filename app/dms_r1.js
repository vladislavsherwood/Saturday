/* dms, круг 1: дни без сигнала (обычный взнос, 18% дней) делим по режиму: «медвежий» → понемногу продавать (DCA-продажа), «бычий» → покупать больше (взнос + f резерва).
   Правила ставятся последними — трогают только дни без сигнала. Критерий (заранее): доход > 0, строгая ✔, 100 новых. Запуск: node dms_r1.js */
const L = require('./r4_lib.js'), { S0, c } = L;
const out = (r) => console.log(r.txt.slice(0, 190));
const R = (rules) => { const S = L.clone(); S.rules.push(...rules); return S; };
const run = (nm, rules) => out(L.run(nm, R(rules), L.pol0, { quiet: true }));
L.run('combo4', S0);
const BEAR = [['монета < 0,8 своей 200д', [c('sma200', '<', 0.8)]], ['монета < 0,9 200д', [c('sma200', '<', 0.9)]], ['монета < 200д', [c('sma200', '<', 1)]],
  ['рост 90д < −20%', [c('ret90', '<', -20)]], ['рост 90д < −30%', [c('ret90', '<', -30)]], ['BTC < 200д', [c('btc200', '<', 1)]], ['BTC < 0,9 200д', [c('btc200', '<', 0.9)]],
  ['монета и BTC < 200д', [c('sma200', '<', 1), c('btc200', '<', 1)]], ['от ATH > 50%', [c('dd', '>', 50)]]];
const BULL = [['монета > 200д', [c('sma200', '>', 1)]], ['монета > 1,2 200д', [c('sma200', '>', 1.2)]], ['BTC > 200д', [c('btc200', '>', 1)]], ['монета и BTC > 200д', [c('sma200', '>', 1), c('btc200', '>', 1)]],
  ['рост 90д > 20%', [c('ret90', '>', 20)]]];
console.log('— A: DCA-продажа в медвежьем режиме —');
for (const [nm, cd] of BEAR) for (const s of [0.005, 0.01, 0.02]) run(`продать ${s * 100}%/день: ${nm}`, [{ act: -s, conds: cd }]);
console.log('— B: DCA-покупка больше в бычьем режиме (взнос + f резерва) —');
for (const [nm, cd] of BULL) for (const f of [0.01, 0.03]) run(`купить +${f * 100}% резерва: ${nm}`, [{ act: 1 + f, conds: cd }]);
console.log('— C: наоборот (проверка смысла): продавать в бычьем, докупать в медвежьем —');
for (const [nm, cd] of BULL.slice(0, 3)) run(`продать 1%: ${nm}`, [{ act: -0.01, conds: cd }]);
for (const [nm, cd] of BEAR.slice(0, 3)) run(`купить +3%: ${nm}`, [{ act: 1.03, conds: cd }]);
