/* imp1, круг 1 (разбор): ценность каждого эпизода разворота. Для эпизода (дата начала s) покупки разворота в днях s…s+60 заменяются
   взносом (или половиной резерва); доход к основе показывает, сколько эпизод приносит. Оценка — только для разбора (даты из будущего не используются в правилах).
   Запуск: node app/imp1_abl.js */
const K = require('./imp1_sim.js');
const G = K.groups(['sel', 'ex', 'rnd']); K.prep(G); K.prep1(G);
const base = K.ev(G, K.S0, false);
const c = K.c;
K.addInd(G, 'tday', (X) => Float64Array.from(X.t));
const EP = ['2017-04-17', '2017-08-05', '2017-10-12', '2018-03-03', '2018-04-28', '2018-07-22', '2019-04-02', '2020-01-14', '2020-07-27', '2020-10-21', '2021-07-30', '2021-10-10', '2022-03-28', '2023-01-14', '2023-03-26', '2023-07-13', '2023-10-23', '2024-02-14', '2024-11-06', '2025-05-06', '2026-08-23'];
for (const e of EP) {
  const s = Date.parse(e) / 864e5;
  const row = [e];
  for (const a of [1, 1.5]) {
    const S = K.mapRev(K.S0, (r) => [{ act: a, conds: [...r.conds, c('tday', '>', s - 1.5), c('tday', '<', s + 60)] }, r]);
    const r = K.ev(G, S, false);
    row.push(`${a === 1 ? 'взнос' : '50%'}: ${K.d(r, base) >= 0 ? '+' : ''}${K.d(r, base).toFixed(3)} (${r.sel.med.toFixed(0)}/${r.ex.med.toFixed(0)}/${r.rnd.med.toFixed(0)})`);
  }
  console.log(row.join(' | '));
}
