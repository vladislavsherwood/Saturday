/* hv, круг 4: продажи у вершины рынка (фандинг 29–31, узкая 32–39 и широкая 40–51 тихие вершины, альтсезон 56, эйфория 57–58) у волатильной монеты крупнее.
   Копия каждого правила семьи перед ним: + hvv > T, не крупная (isbig < 0,5), доля × m (не больше 100%). Сравнение — к combo5 и к лучшей точке круга 2. */
const H = require('./hv_lib.js'), { c } = H;
const NB = [c('isbig', '<', 0.5)];
const mod = (T, m, ex = []) => (r) => { r.conds.push(...H.HV(T), ...NB, ...ex); r.act = H.mul(m)(r.act); return r; };
const F = { 'фандинг': (r, k) => k >= 28 && k <= 30, 'узкая вершина': (r, k) => k >= 31 && k <= 38, 'широкая вершина': (r, k) => k >= 39 && k <= 50,
  'альтсезон': (r, k) => k === 55, 'эйфория': (r, k) => k === 56 || k === 57, 'все вершины': (r, k) => (k >= 28 && k <= 50) || (k >= 55 && k <= 57) };
H.head();
H.ev('combo5', H.S5);
for (const [nm, pick] of Object.entries(F)) for (const m of [1.5, 2]) H.ev(`T115 ${nm} ×${m}`, H.preMod(H.S5, pick, mod(115, m)));
for (const T of [100, 130]) H.ev(`T${T} все вершины ×1.5`, H.preMod(H.S5, F['все вершины'], mod(T, 1.5)));
// «светофор» C4 по волатильности: все продажи ×1,5, если монета ниже своей 200д
const ALLS = (r, k) => r.act < 0;
for (const m of [1.25, 1.5]) H.ev(`T115 все продажи ×${m} и монета < 200д`, H.preMod(H.S5, ALLS, mod(115, m, [c('sma200', '<', 1)])));
