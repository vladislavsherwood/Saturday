/* h1, круг 3: форма хранения резерва — доля w резерва в BTC (или в самой монете), остальное в стейблах; перестройка по вчерашним данным, комиссия 0,1%.
   Варианты: всегда w; только когда BTC выше своей 200д (тренд); в самой монете при монете выше 200д. Запуск: node h1_r3.js */
const H = require('./h1_lib.js');
H.head();
const st = (o) => H.mk(H.store(o));
H.ev('BTC 25% всегда', st({ w: () => 0.25 }));
H.ev('BTC 50% всегда', st({ w: () => 0.5 }));
H.ev('BTC 50% при BTC > 200д', st({ w: (X, j) => (X.ind.btc200[j] > 1 ? 0.5 : 0) }), { n100: true });
H.ev('BTC 100% при BTC > 200д', st({ w: (X, j) => (X.ind.btc200[j] > 1 ? 1 : 0) }));
H.ev('BTC 50% при BTC > 1,1 × 200д', st({ w: (X, j) => (X.ind.btc200[j] > 1.1 ? 0.5 : 0) }));
H.ev('BTC 50% при BTC > 200д и usdt < 1', st({ w: (X, j) => (X.ind.btc200[j] > 1 && X.ind.usdt[j] < 1 ? 0.5 : 0) }));
H.ev('BTC 50% при BTC > 200д, не BTC', st({ w: (X, j) => (X.name !== 'BTC' && X.ind.btc200[j] > 1 ? 0.5 : 0) }));
H.ev('монета 50% при монете > 200д', st({ w: (X, j) => (X.ind.sma200[j] > 1 ? 0.5 : 0), asset: 'coin' }));
H.ev('монета 50% при монете и BTC > 200д', st({ w: (X, j) => (X.ind.sma200[j] > 1 && X.ind.btc200[j] > 1 ? 0.5 : 0), asset: 'coin' }));
H.ev('BTC 50% при BTC > 200д + векселя на стейблах', st({ w: (X, j) => (X.ind.btc200[j] > 1 ? 0.5 : 0), save: 'tb' }), { n100: true });
