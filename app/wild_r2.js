/* Круг 2. Структура рынка: «стадность» (средняя корреляция альтов с BTC за 30 дней, wild_mkt.js) как признак капитуляции.
   Диагностика (scratchpad/wild/diag2.log): при herd30 в верхних 10% прошлых значений BTC +36% за 90 дней, покупки combo4 +49%, продажи — цена +5,8% (продавали зря).
   Варианты (правило вставляется после охраны #10, т. е. ниже всех покупок паники/дна, выше всех продаж):
     А «не продавать»: стадность → только взнос (act 1);   Б «докупить»: стадность → взнос + y резерва.
   Порог: абсолютный herd30 > h или процентиль herd30_pr > p. Запуск: node wild_r2.js > scratchpad/wild/r2.log */
const W = require('./wild_sim.js'); require('./wild_mkt.js')(W.G);
// исправлено: правило-вставка перехватывало разворот BTC (btcr30 > 20 → весь резерв), поэтому — крючок: А меняет только продажи, Б — только дни без более крупной покупки
const hkA = (ind, v, to = 1) => ({ act: ({ X, j, a }) => (a < 0 && X.ind[ind][j] > v ? to : a) });
const hkB = (ind, v, y) => ({ act: ({ X, j, a }) => (a <= 1 + y && X.ind[ind][j] > v ? 1 + y : a) });
W.report('combo4');
for (const [ind, vs] of [['herd30', [0.75, 0.8, 0.85]], ['herd30_pr', [0.85, 0.9, 0.95]]])
  for (const v of vs) {
    W.report(`А ${ind}>${v} не продавать, взнос в резерв`, W.BASE, W.POL, hkA(ind, v, 0));
    W.report(`А ${ind}>${v} не продавать`, W.BASE, W.POL, hkA(ind, v));
    for (const y of [0.1, 0.25]) W.report(`Б ${ind}>${v} докупить ${y * 100}%`, W.BASE, W.POL, hkB(ind, v, y));
  }
// контроль: дисперсия (низкая — продажи точнее) и широта новых максимумов (> 30% монет у 90-дн. максимума — продажи хуже)
for (const v of [20, 30, 40]) W.report(`hi90f>${v} не продавать`, W.BASE, W.POL, hkA('hi90f', v));
console.log(W.summary());
