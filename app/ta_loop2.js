/* Агент ТА, круг 2: подтверждение разворота «BTC +20% за 30 дней» структурой рынка (доп. условие внутри правила, вариант (д), и замена порога (г)).
   Гипотеза (заранее): ложные развороты медвежьего рынка (2018-03/04/07, 2022-03/07) идут без нового максимума BTC за 4 недели (HH: максимум
   последних W дней выше максимума W дней до них). Если правила возврата резерва (#10 «разворот + фандинг», #18 «разворот») срабатывают только
   при HH, резерв не тратится на медвежьи ралли и уходит ниже; хорошие развороты (2019-04, 2020-05…12, 2023-01/10, 2024-11) HH имеют.
   Плато — окно W = 14/21/28/35/42 дня (по максимумам и по закрытиям); неподтверждённый день — пропуск правила или часть резерва (25%).
   Сравнение с другими подтверждениями ТА (BTC выше 20/50-недельной средней, MACD BTC > 0, HL — минимум выше прошлого).
   Критерий: общий (строгая ✔, доход > +0,03, соседние W > 0, 100 новых не хуже по монетам/половинам); дополнительно — смягчает ли HH обрыв
   порога (доход при btcr30 > 17/18/19 с HH не ниже −0,1 к основе). Запуск: node app/ta_loop2.js > log */
const T = require('./ta_sim.js');
const { c } = T;
const G = T.load();
// HH/HL BTC с окном W (по максимумам/минимумам дня или по закрытиям)
for (const W of [14, 21, 28, 35, 42]) {
  T.addB(G, 'bhh' + W, (cl, h, l) => { const m = T.rollMax(h, W); return cl.map((x, i) => (i >= 2 * W && m[i] > m[i - W] ? 1 : 0)); });
  T.addB(G, 'bhc' + W, (cl) => { const m = T.rollMax(cl, W); return cl.map((x, i) => (i >= 2 * W && m[i] > m[i - W] ? 1 : 0)); });
  T.addB(G, 'bhl' + W, (cl, h, l) => { const m = T.rollMin(l, W); return cl.map((x, i) => (i >= 2 * W && m[i] > m[i - W] ? 1 : 0)); });
}
const base = T.ev(G, T.BASE), out = [];
const run = (t, S) => { const r = T.ev(G, S); out.push({ t, d: T.K.d(r, base), pass: T.K.passes(r, base), n100: r.n100.med, n100pos: r.n100.pos, n100h: r.n100.hpos, m: r.m }); console.log(T.rowS(t, r, base)); return r; };
console.log(T.K.HDR); console.log(T.rowS('основа', base, base));
const rev = (r) => T.isRev(r) && r.act > 1; // #10 и #18 (#9 «разворот на страхе — только взнос» не трогаю)
// пропуск: правило срабатывает только при условии; часть: без условия — только 25% резерва
const conf = (S, conds, part) => (part == null ? T.addC(S, (r) => rev(r), conds) : { ...S, rules: S.rules.flatMap((r) => (rev(r) ? [{ ...r, conds: [...r.conds, ...conds] }, { ...r, act: part }] : [r])) });
for (const W of [14, 21, 28, 35, 42]) {
  run(`HH${W} (по максимумам), иначе пропуск`, conf(T.BASE, [c('bhh' + W, '>', 0.5)]));
  run(`HH${W} (по закрытиям), иначе пропуск`, conf(T.BASE, [c('bhc' + W, '>', 0.5)]));
  run(`HH${W}, иначе 25% резерва`, conf(T.BASE, [c('bhh' + W, '>', 0.5)], 1.25));
  run(`HL${W} (минимум выше), иначе пропуск`, conf(T.BASE, [c('bhl' + W, '>', 0.5)]));
}
for (const [k, v, nm] of [['b_w20', 1, 'BTC выше 20-нед. средней'], ['b_w50', 1, 'BTC выше 50-нед. средней'], ['b_macd', 0, 'MACD BTC > 0'], ['b_w200', 1.2, 'BTC > 1,2 × 200-нед. средней']])
  run(`${nm}, иначе пропуск`, conf(T.BASE, [c(k, '>', v)]));
// обрыв порога: btcr30 > x во всех трёх правилах разворота, с HH28 и без
const thr = (S, x) => ({ ...S, rules: S.rules.map((r) => (T.has(r, 'btcr30') ? { ...r, conds: r.conds.map((q) => (q.ind === 'btcr30' ? { ...q, v: x } : q)) } : r)) });
for (const x of [15, 17, 18, 19, 22, 25]) {
  run(`порог ${x} без подтверждения`, thr(T.BASE, x));
  run(`порог ${x} + HH28`, conf(thr(T.BASE, x), [c('bhh28', '>', 0.5)]));
}
require('fs').writeFileSync(process.argv[2] || '/dev/null', JSON.stringify(out));
