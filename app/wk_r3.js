/* wk, круг 3: (a) состояние рынка до выставления заявок (без минимумов других монет того же дня) — множитель долей на окно:
   перегрев плеча (рост OI за 30 дн, фандинг), страх, медвежий рынок BTC, «нож» по своей цене;
   (b) реальность исполнения: пробой лимита, порядок (фитиль до сделки правила), комиссия мейкера, минимальная заявка ($5 / 0,01 монеты)
   при взносе пользователя $2 и $1 в день (масштаб стенда 10 / взнос), объединение мелких уровней.
   Основа круга — B1 = −25/−40/−60 → 10/20/30, раз в 3 дня, once, place. Запуск: node wk_r3.js > scratchpad/wk/r3.log */
const W = require('./wk_lib.js'), { ev, pol } = W;
const B1 = { every: 3, once: 1, size: 'place' };
const M = (ind, op, v, k) => (X, j) => { const x = X.ind[ind][j]; return isFinite(x) && (op === '>' ? x > v : x < v) ? k : 1; };
W.head();
const b = ev('B1', pol(B1), { n100: true });
console.log('— (a) множитель долей по состоянию рынка на день выставления —');
for (const [nm, ind, op, vs, k] of [
  ['перегрев: рост OI BTC 30 дн >', 'oic30', '>', [10, 20], 1.5],
  ['перегрев: фандинг 7 дн >', 'fund7', '>', [0.2, 0.4], 1.5],
  ['перегрев: лонги/шорты >', 'lsr', '>', [1.25, 1.5], 1.5],
  ['уже страх: fng <', 'fng', '<', [20, 30], 0.5],
  ['жадность: fng >', 'fng', '>', [65, 75], 1.5],
  ['медвежий BTC: BTC/200д <', 'btc200', '<', [0.9, 1], 0.5],
  ['бычий BTC: BTC/200д >', 'btc200', '>', [1.1, 1.25], 1.5],
  ['нож: монета/200д <', 'sma200', '<', [0.5, 0.65], 0.5],
  ['нож: просадка за год >', 'dd365', '>', [75, 85], 0.5],
  ['каскад начался: вчера монета < −10% / −15%', 'ret1', '<', [-10, -15], 1.5],
]) for (const v of vs) ev(`${nm} ${v} → ×${k}`, pol({ ...B1, mult: M(ind, op, v, k) }), { n100: true });
console.log('— (b) реальность исполнения —');
for (const tt of [0.01, 0.02, 0.03]) ev(`пробой лимита ${tt * 100}%`, pol({ ...B1, tt }), { n100: true });
ev('фитиль до сделки правила (first)', pol({ ...B1, first: 1 }), { n100: true });
ev('комиссия мейкера 0,02%', pol({ ...B1, fee: 0.0002 }), { n100: true });
for (const u of [2, 1]) {
  const s = 10 / u;
  for (const merge of [0, 'down', 'up']) ev(`мин. заявка перп Bybit, взнос $${u}: ${merge ? 'объединить ' + merge : 'пропустить'}`, pol({ ...B1, min: (X, lim) => s * Math.max(5, 0.01 * lim), merge }), { n100: true });
  ev(`мин. заявка спот $5, взнос $${u}: объединить down`, pol({ ...B1, min: 5 * s, merge: 'down' }), { n100: true });
}
const s = 5; ev('всё вместе: пробой 1%, first, мейкер 0,02%, мин. перп при $2, объединить down', pol({ ...B1, tt: 0.01, first: 1, fee: 0.0002, min: (X, lim) => s * Math.max(5, 0.01 * lim), merge: 'down' }), { n100: true });
