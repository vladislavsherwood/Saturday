/* hv, круг 1: разворот BTC (правило 28, btcr30 > 20 → весь резерв) осторожнее у волатильной монеты, которая сама уже выросла в разы от минимума.
   Копия правила 28 перед ним: hvv > T и рост монеты (up90 > U или монета > k × своей 200д) → act a (1 — взнос; 1e-6 — копить; 1,25 / 1,5 — четверть / половина резерва). */
const H = require('./hv_lib.js'), { c } = H;
const R27 = (r, k) => k === 27;
H.head();
H.ev('combo5', H.S5);
for (const T of [100, 115, 130]) for (const U of [100, 200, 300]) for (const a of [1, 1e-6, 1.5])
  H.ev(`T${T} up90>${U} → ${a === 1 ? 'взнос' : a < 1 ? 'копить' : a}`, H.pre(H.S5, R27, [...H.HV(T), c('up90', '>', U)], a));
for (const T of [115]) for (const k of [1.5, 2, 3]) for (const a of [1, 1.5])
  H.ev(`T${T} sma200>${k} → ${a === 1 ? 'взнос' : a}`, H.pre(H.S5, R27, [...H.HV(T), c('sma200', '>', k)], a));
// без условия волатильности (контроль: так отвергнуто в h3)
for (const U of [200, 300]) H.ev(`все монеты up90>${U} → взнос`, H.pre(H.S5, R27, [c('up90', '>', U)], 1));
