/* au, круг 9: золото как фильтр к существующим правилам combo6.
   (а) «бегство в защиту»: паника крипты, а золото +X% за 30 дн → покупки паники 0–8 ×0,5 (отложить) / ×1,5; (б) паника крипты и золото тоже падает (au_r30 < −X) → ×1,5;
   (в) продажи на страхе 11–26 ×1,5 при «бегстве в защиту» (золото +X%); (г) правило 27 (BTC +20% за 30 дн → взнос + 100% резерва) только если золото не растёт (au_r30 < X), иначе взнос;
   (д) эйфория (70–75) и вершина (39–68) ×1,5 / ×0,5, если золото на 250-дн. максимуме. Запуск: node au_r9.js > scratchpad/au/r9.txt */
const A = require('./au_lib.js'), { c, S6 } = A;
const rows = [];
const R = (nm, S) => { const r = A.run(nm, S); rows.push([nm, r]); return r; };
const mod = (pick, cond, f) => A.preMod(S6, (r, q) => pick(q), (r) => ({ act: +f(r.act).toFixed(6), conds: [...r.conds, ...cond] }));
const buy = (q) => q <= 8, fear = (q) => q >= 11 && q <= 26, eu = (q) => q >= 70, top = (q) => q >= 39 && q <= 68 && q !== 59;
for (const x of [2, 3, 5]) {
  R(`(а) паника, золото +${x}%/30д: ×0,5`, mod(buy, [c('au_r30', '>', x)], (a) => 1 + (a - 1) * 0.5));
  R(`(а) паника, золото +${x}%/30д: ×1,5`, mod(buy, [c('au_r30', '>', x)], (a) => 1 + (a - 1) * 1.5));
  R(`(б) паника, золото −${x}%/30д: ×1,5 age>180`, mod(buy, [c('au_r30', '<', -x), c('age', '>', 180)], (a) => 1 + (a - 1) * 1.5));
  R(`(в) страх, золото +${x}%/30д: продажа ×1,5`, mod(fear, [c('au_r30', '>', x)], (a) => Math.max(-1, a * 1.5)));
  R(`(г) пр.27 только если золото < +${x}%`, mod((q) => q === 27, [c('au_r30', '>', x)], () => 1));
}
for (const [nm, ind, op, v] of [['золото на 250д максимуме', 'au_hi250', '>', 0.5], ['золото у рекорда (≤ 5 дн.)', 'au_hid', '<', 5.5], ['золото −10% от рекорда', 'au_ath', '>', 10]]) for (const m of [0.5, 1.5]) {
  R(`(д) эйфория ×${m}: ${nm}`, mod(eu, [c(ind, op, v)], (a) => Math.max(-1, a * m)));
  R(`(д) вершина ×${m}: ${nm}`, mod(top, [c(ind, op, v)], (a) => Math.max(-1, a * m)));
}
const ok = rows.filter(([, r]) => !r.w && r.dseg.all > 0 && r.n100 && r.n100.m > 0 && r.n100.u > r.n100.d && r.hv.h1 > -0.005 && r.hv.h2 > -0.005);
console.log('\nпрошли критерий 1, 2, 4:', ok.map(([nm, r]) => `${nm} ${A.sg(r.dseg.all)}`).join('; ') || 'нет');
