/* st, круг 4 — добавляет ли отставание от акций что-то сверх собственного падения BTC? И держится ли «не продавать на страхе» не на одном эпизоде.
   (а) плато по BTC−NDX 90д и по BTC за 90д; (б) пересечения: BTC −25% за 90д И акции росли (крипта отстала сама) / И акции падали (общий риск-офф);
   (в) без крупных (isbig < 0,5) — правка строгой по крупным; (г) по одному эпизоду: правило выключено внутри окна (2018, 2019, 2021-05…08, 2022, 2025-11…2026-02).
   Запуск: node st_r4.js */
const ST = require('./st_lib.js'), { c, L, T } = ST;
const FEAR = [c('usdtd', '<', 7.6), c('fng', '<', 52)];
const hold = (conds, act = 1e-6) => ST.ins([{ act, conds: [...FEAR, ...conds] }], 11);
const go = (nm, S) => ST.ev(nm, S);
console.log('(а) плато');
for (const x of [-32, -35, -38, -41, -44, -47]) go(`BTC−NDX 90д < ${x}`, hold([c('st_bxr90', '<', x)]));
for (const x of [-15, -20, -25, -30]) go(`BTC за 90д < ${x}`, hold([c('btcr90', '<', x)]));
console.log('(б) пересечения');
go('BTC 90д < −25 И NDX 90д > 0', hold([c('btcr90', '<', -25), c('st_ndxr90', '>', 0)]));
go('BTC 90д < −25 И NDX 90д < 0', hold([c('btcr90', '<', -25), c('st_ndxr90', '<', 0)]));
go('BTC 90д < −25 И NDX 90д > −5', hold([c('btcr90', '<', -25), c('st_ndxr90', '>', -5)]));
go('BTC 90д < −25 И BTC−NDX 90д < −30', hold([c('btcr90', '<', -25), c('st_bxr90', '<', -30)]));
go('BTC 90д < −20 И BTC−NDX 90д < −30', hold([c('btcr90', '<', -20), c('st_bxr90', '<', -30)]));
go('BTC 90д < −25 И NDX > 200д', hold([c('btcr90', '<', -25), c('st_ndx200', '>', 1)]));
go('BTC 90д < −25 И NDX < 200д', hold([c('btcr90', '<', -25), c('st_ndx200', '<', 1)]));
go('BTC 90д < −25 И корр 90 < 0,4', hold([c('btcr90', '<', -25), c('st_bxc90', '<', 0.4)]));
go('BTC 90д < −25 И корр 90 > 0,4', hold([c('btcr90', '<', -25), c('st_bxc90', '>', 0.4)]));
console.log('(в) без крупных');
for (const x of [-35, -40]) go(`BTC−NDX 90д < ${x}, не крупные`, hold([c('st_bxr90', '<', x), c('isbig', '<', 0.5)]));
go('BTC 90д < −25, не крупные', hold([c('btcr90', '<', -25), c('isbig', '<', 0.5)]));
console.log('(г) по одному эпизоду: правило выключено в окне');
const W = [['2018', '2018-01-01', '2018-11-01'], ['2018-11…2019-02', '2018-11-01', '2019-03-01'], ['2019-09…12', '2019-09-01', '2020-01-01'], ['2021-05…08', '2021-05-01', '2021-09-01'], ['2022', '2022-01-01', '2023-01-01'], ['2025-11…2026-02', '2025-11-01', '2026-03-01']];
W.forEach(([nm, a, b], k) => L.addInd('st_w' + k, (X) => Float64Array.from(X.ind.t, (t) => (t >= T(a) && t < T(b) ? 1 : 0))));
for (const [lab, conds] of [['BTC−NDX 90д < −38', [c('st_bxr90', '<', -38)]], ['BTC 90д < −25', [c('btcr90', '<', -25)]]])
  W.forEach(([nm], k) => go(`${lab} без ${nm}`, hold([...conds, c('st_w' + k, '<', 0.5)])));
