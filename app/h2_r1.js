/* h2, круг 1: «зона дна цикла» — рыночный признак капитуляции (MVRV BTC < m; BTC / 200-нед. < w; BTC ниже ATH > X) и действие в зоне.
   Место правила: после правил покупки 1–9 и охраны 10 (паника, капитуляция страха, выносы, охрана после разворота — как были), перед продажами на страхе 11–26;
   условие btcr30 < 20 — чтобы не заслонять разворот BTC (правило 27). Действия: «копить» (act 1e-6: не продавать, взнос в резерв), «взнос» (1), «+f резерва в день».
   Вариант «страх»: то же только при страхе < q (в остальные дни зоны продажи на страхе остаются).
   Основа — combo4 + фитили (и проверка на combo4). Запуск: node h2_r1.js [wick|plain] */
const H = require('./h2_lib.js'), { L, c } = H;
const kind = process.argv[2] || 'wick', pol = H.base(kind);
console.log(`ОСНОВА: combo4 (57)${kind === 'wick' ? ' + фитили' : ''}`);
H.run('основа', H.S57, pol);
const Z = (zc, act, extra = []) => ({ act, conds: [...zc, ...extra, c('btcr30', '<', 20)] });
const zones = {
  'mvrv<0,9': [c('mvrv', '<', 0.9)], 'mvrv<1': [c('mvrv', '<', 1)], 'mvrv<1,1': [c('mvrv', '<', 1.1)],
  'wma<1': [c('h2wma', '<', 1)], 'wma<1,2': [c('h2wma', '<', 1.2)],
  'ath>70': [c('btcath', '>', 70)], 'ath>75': [c('btcath', '>', 75)],
};
const out = [];
for (const [zn, zc] of Object.entries(zones)) {
  for (const [an, act] of [['копить', 1e-6], ['взнос', 1], ['+2%', 1.02], ['+5%', 1.05], ['+10%', 1.1]]) out.push(H.run(`${zn} → ${an}`, H.ins([Z(zc, act)], 10), pol, { n100: true }));
  for (const q of [20, 25]) for (const [an, act] of [['+5%', 1.05], ['+10%', 1.1], ['+25%', 1.25]]) out.push(H.run(`${zn}, страх<${q} → ${an}`, H.ins([Z(zc, act, [c('fng', '<', q)])], 10), pol, { n100: true }));
}
