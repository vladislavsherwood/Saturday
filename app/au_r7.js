/* au, круг 7: идеи пользователя — «золото обновляет максимумы, BTC отстаёт → крипта догонит» и «BTC/золото ниже своей средней → крипта перепродана к золоту».
   (а) покупка f, если золото ≤ 5 дн. от рекорда и BTC/золото за 90 дн < −X%; (б) то же, но только отмена продаж (act 1); (в) покупка f, если BTC/золото < k своей 200д / 365д;
   (г) монета/золото за 90 дн < −X% (своя перепроданность к золоту). Места: в конце (обычные дни) и @11 (после покупок, перекрывает продажи).
   Запуск: node au_r7.js > scratchpad/au/r7.txt */
const A = require('./au_lib.js'), { c, S6 } = A;
const rows = [];
const R = (nm, S) => { const r = A.run(nm, S); rows.push([nm, r]); return r; };
const END = S6.rules.length;
for (const x of [10, 20, 30]) {
  const cd = [c('au_hid', '<', 5.5), c('bg_r90', '<', -x)];
  R(`(а) рекорд золота, BTC/зол −${x}% 90д, +0.1 в конце`, A.ins([{ act: 1.1, conds: cd }], END));
  R(`(а) то же @11`, A.ins([{ act: 1.1, conds: cd }], 11));
  R(`(б) рекорд золота, BTC/зол −${x}% 90д, не продавать`, A.ins([{ act: 1, conds: cd }], 11));
}
for (const [ind, ks] of [['bg_s200', [0.7, 0.75, 0.8]], ['bg_s365', [0.7, 0.8, 0.9]]]) for (const k of ks) {
  R(`(в) ${ind} < ${k}, +0.1 в конце`, A.ins([{ act: 1.1, conds: [c(ind, '<', k)] }], END));
  R(`(в) ${ind} < ${k}, +0.1 @11`, A.ins([{ act: 1.1, conds: [c(ind, '<', k)] }], 11));
}
for (const x of [30, 40, 50]) { R(`(г) монета/золото −${x}% 90д, +0.1 в конце`, A.ins([{ act: 1.1, conds: [c('cg_r90', '<', -x)] }], END)); R(`(г) то же @11`, A.ins([{ act: 1.1, conds: [c('cg_r90', '<', -x)] }], 11)); }
const ok = rows.filter(([, r]) => !r.w && r.dseg.all > 0 && r.n100 && r.n100.m > 0 && r.n100.u > r.n100.d && r.hv.h1 > -0.005 && r.hv.h2 > -0.005);
console.log('\nпрошли критерий 1, 2, 4:', ok.map(([nm, r]) => `${nm} ${A.sg(r.dseg.all)}`).join('; ') || 'нет');
