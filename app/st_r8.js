/* st, круг 8 — «акции сильные, крипта слабая → покупать» (идея пользователя в прямом виде).
   Диагностика круга 1: NDX > 200д и BTC < 200д → монеты +7,7% за 90 дн к обычному (132/181), держится без 2020-03/2022/2025-10, но у самого BTC −7%;
   лог BTC/NDX к 200д < −30 → +8,6% (123/181); BTC−NDX 30д < −20 → +11,4% (139/181); «акции у максимума, BTC −25% от года» → −2,4% (нет).
   Варианты: (а) в дни без сигнала (последним): взнос + f резерва; (б) перед продажами на страхе (позиция 12): копить / взнос + f;
   (в) копии покупок 1–9 × m. Запуск: node st_r8.js */
const ST = require('./st_lib.js'), { c, S6 } = ST;
const go = (nm, S) => ST.ev(nm, S);
const R6 = (x) => Math.round(x * 1e6) / 1e6;
const SIG = [['NDX > 200д И BTC < 200д', [c('st_ndx200', '>', 1), c('btc200', '<', 1)]], ['NDX > 200д И BTC < 0,85 200д', [c('st_ndx200', '>', 1), c('btc200', '<', 0.85)]],
  ['лог BTC/NDX к 200д < −30', [c('st_bxz', '<', -30)]], ['BTC−NDX 30д < −20', [c('st_bxr30', '<', -20)]], ['BTC−NDX 90д < −40', [c('st_bxr90', '<', -40)]],
  ['акции у макс., BTC −25% от года', [c('st_bxdiv', '>', 0.5)]]];
console.log('(а) дни без сигнала → взнос + f резерва');
for (const [nm, cs] of SIG) for (const f of [0.05, 0.15]) go(`${nm} → +${f}`, ST.ins([{ act: 1 + f, conds: cs }], S6.rules.length));
console.log('(б) позиция 12 (перед продажами на страхе) → взнос + f');
for (const [nm, cs] of SIG.slice(0, 3)) for (const f of [0, 0.1]) go(`${nm} → поз.12 +${f}`, ST.ins([{ act: 1 + f, conds: cs }], 11));
console.log('(в) копии покупок 1–9 × m');
for (const [nm, cs] of SIG.slice(0, 4)) go(`покупки ×1,5 при ${nm}`, ST.preMod((r, k) => k <= 8, (r) => ({ act: R6(1 + (r.act - 1) * 1.5), conds: [...r.conds, ...cs] })));
