/* h4, круг 1: разворот BTC (правило 27, btcr30 > 20 → весь резерв) в «отскоке медвежьего рынка» (2019-04: BTC ниже своей 200д) и у слабых монет.
   Копия правила 27 с доп. условием и меньшей долей — перед ним. Основа: combo4 + фитили. Запуск: node h4_r1.js */
const H = require('./h4_lib.js'), { L, S57, polW, c } = H;
H.setBase(S57, polW);
const R27 = 27;
const V = [];
for (const [lab, cond] of [['BTC < 200д', [c('btc200', '<', 1)]], ['BTC < 0,95 200д', [c('btc200', '<', 0.95)]], ['BTC < 1,05 200д', [c('btc200', '<', 1.05)]],
  ['монета < 0,8 своей 200д', [c('sma200', '<', 0.8)]], ['монета < 200д', [c('sma200', '<', 1)]], ['rel90 < −25', [c('rel90', '<', -25)]], ['rel180 < −30', [c('rel180', '<', -30)]],
  ['BTC < 200д и доля альтов падает (oth90 < 0)', [c('btc200', '<', 1), c('oth90', '<', 0)]]])
  for (const a of [1.5, 1.1, 1.03, 1]) V.push([`27 при ${lab} → ${a}`, H.withCopies(S57, [R27], cond, () => a)]);
for (const [nm, S] of V) H.run(nm, S, polW);
