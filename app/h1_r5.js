/* h1, круг 5: мелкая лестница лимиток на покупку из резерва поверх фитилей (раз в 3 дня, раз за окно, по минимуму дня), режим всегда / бычий (монета и BTC > 200д),
   выход: держать / к опорной цене (грид) / +10%. Запуск: node h1_r5.js */
const H = require('./h1_lib.js');
H.head();
const bull = (X, j) => X.ind.sma200[j] > 1 && X.ind.btc200[j] > 1;
const LV = { 'L5: −5/10/15 → 3/5/7': [[0.05, 0.03], [0.1, 0.05], [0.15, 0.07]], 'L8: −8/12/16 → 5/7/10': [[0.08, 0.05], [0.12, 0.07], [0.16, 0.1]], 'L10: −10/15/20 → 5/8/10': [[0.1, 0.05], [0.15, 0.08], [0.2, 0.1]] };
for (const [ln, lv] of Object.entries(LV)) for (const when of [null, bull]) for (const exit of [null, 'ref', 0.1])
  H.ev(`${ln}${when ? ' бык' : ''}${exit ? ' выход ' + exit : ''}`, H.mk(H.ladder({ lv, when, exit })));
