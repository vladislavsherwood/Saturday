/* dms, круг 2: дни без сигнала делим на «купить взнос» (как сейчас) и «продать» — взнос дня не покупается, а продаётся немного монеты.
   Продажа: доля позиции (0,25 / 0,5 / 1%) или на сумму 1 / 2 взносов (зеркало DCA). Правило последним — только дни без сигнала.
   Критерий (заранее): доход > 0, строгая ✔, затем 100 новых и соседи. Запуск: node dms_r3.js */
const L = require('./r4_lib.js'), { S0, c } = L;
const res = [];
const T = (nm, conds) => {
  for (const [sn, rule] of [['−0,25%', { act: -0.0025 }], ['−0,5%', { act: -0.005 }], ['−1%', { act: -0.01 }], ['−1 взнос', { act: -1e-9, sellU: 1 }], ['−2 взноса', { act: -1e-9, sellU: 2 }]]) {
    const S = L.clone(); S.rules.push({ ...rule, conds }); const o = L.run(`${nm}: ${sn}`, S, L.pol0, { quiet: true }); res.push({ nm: `${nm}: ${sn}`, inc: o.dseg.all, ok: !o.w, o });
  }
};
L.run('combo4', S0);
const C = [
  ['монета > 1,2 своей 200д', [c('sma200', '>', 1.2)]], ['монета > 1,5 200д', [c('sma200', '>', 1.5)]], ['монета > 2 200д', [c('sma200', '>', 2)]],
  ['жадность > 60', [c('fng', '>', 60)]], ['жадность > 70', [c('fng', '>', 70)]], ['жадность > 80', [c('fng', '>', 80)]],
  ['RSI > 65', [c('rsi', '>', 65)]], ['RSI > 70', [c('rsi', '>', 70)]], ['рост 90д > 50%', [c('ret90', '>', 50)]], ['рост 90д > 100%', [c('ret90', '>', 100)]],
  ['у ATH (< 10%)', [c('dd', '<', 10)]], ['у ATH (< 20%)', [c('dd', '<', 20)]], ['usdt < 0,95', [c('usdt', '<', 0.95)]], ['usdt < 1', [c('usdt', '<', 1)]],
  ['BTC > 1,2 200д', [c('btc200', '>', 1.2)]], ['монета и BTC > 200д', [c('sma200', '>', 1), c('btc200', '>', 1)]],
  ['монета > 1,2 200д и жадность > 60', [c('sma200', '>', 1.2), c('fng', '>', 60)]], ['мем и монета > 1,2 200д', [c('meme', '>', 0.5), c('sma200', '>', 1.2)]],
  ['мем и жадность > 60', [c('meme', '>', 0.5), c('fng', '>', 60)]],
  ['монета < 0,8 200д (падение)', [c('sma200', '<', 0.8)]], ['монета и BTC < 200д (падение)', [c('sma200', '<', 1), c('btc200', '<', 1)]],
];
for (const [nm, cd] of C) T(nm, cd);
res.sort((a, b) => b.inc - a.inc);
console.log(`вариантов ${res.length}; в плюсе ${res.filter((r) => r.inc > 0).length}; в плюсе и строгая ✔ ${res.filter((r) => r.inc > 0 && r.ok).length}`);
console.log('лучшие 12:'); for (const r of res.slice(0, 12)) console.log(r.o.txt.slice(0, 200));
console.log('худшие 3:'); for (const r of res.slice(-3)) console.log(r.o.txt.slice(0, 160));
require('fs').writeFileSync(process.argv[2] || '/dev/null', JSON.stringify(res.map(({ nm, inc, ok }) => ({ nm, inc, ok }))));
