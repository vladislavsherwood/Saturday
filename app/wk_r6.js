/* wk, круг 6 (дополнительный, по просьбе пользователя): «фитильная продажа» — зеркало ловушки: постоянные лимитки на продажу выше опорной цены
   (+25/+40/+60%, доли позиции), исполнение по лимиту, если максимум дня ≥ лимита; выручка — в резерв монеты.
   A — чистая продажа на combo4 и контроль «та же продажа по закрытию дня»; B — фильтры режима (стратегия недавно продавала, эйфория, жадность,
   монета высоко над 200д, только альты/мемы/крупные); C — переработка: после продажи лимитка на откуп ниже; D — вместе с покупочной ловушкой (финалист).
   Запуск: node wk_r6.js > scratchpad/wk/r6.log */
const W = require('./wk_lib.js'), { ev, pol0, P, G, S0, L } = W;
const FIN = { every: 3, once: 1, size: 'place', lv: [[0.25, 0.15], [0.4, 0.25], [0.6, 0.35]], age: 60 };
const SB = { every: 3, once: 1, size: 'place', age: 60 };
const LS = (fs, ks = [0.25, 0.4, 0.6]) => ks.map((k, q) => [k, fs[q]]);
const S = (o = {}, buy = false) => ({ ...pol0, ...(buy ? { wick: FIN } : {}), wickS: { ...SB, lv: LS([0.1, 0.2, 0.3]), ...o } });
// индикатор «стратегия продавала за последние 30 дней» (по решениям combo4 без сдвига, только прошлое): sold30[j] = 1, если решение продать было в j−29…j
L.addInd('sold30', (X) => { const { tr } = P.edge(X, S0, 0, 'full', true, pol0), a = new Float64Array(X.n); const d = tr.filter((t) => t.s < 0).map((t) => t.i - 1); for (const j of d) for (let k = j; k < Math.min(X.n, j + 30); k++) a[k] = 1; return a; });
const I = (ind, op, v) => (X, j) => { const x = X.ind[ind][j]; return isFinite(x) && (op === '>' ? x > v : x < v); };
W.head();
const c4 = ev('combo4', pol0, { n100: true });
const fin = ev('ФИНАЛИСТ покупочной ловушки (15/25/35)', { ...pol0, wick: FIN }, { n100: true });
const d = (o, b) => `   к основе: доход ${W.sg(o.all - b.all)} (к ${W.sg(o.big - b.big, 2)} а ${W.sg(o.alt - b.alt, 2)} м ${W.sg(o.meme - b.meme, 2)}) | 81 ${W.sg(o.m81 - b.m81)} | 100н ${W.sg(o.n - b.n)}`;
const run = (nm, p, b = c4) => { const o = ev(nm, p, { n100: true }); console.log(d(o, b)); return o; };
console.log('— A: чистая фитильная продажа на combo4 (раз в 3 дня, уровень раз за окно, доля позиции на момент выставления) —');
for (const fs of [[0.05, 0.05, 0.05], [0.05, 0.1, 0.15], [0.1, 0.2, 0.3]]) {
  run(`продажа +25/40/60: ${fs.map((x) => x * 100).join('/')}%`, S({ lv: LS(fs) }));
  run(`   контроль: по закрытию дня`, S({ lv: LS(fs), mode: 'close' }));
}
run('продажа 5/10/15, каждый день', S({ lv: LS([0.05, 0.1, 0.15]), every: 1 }));
run('продажа +15/25/40: 5/10/15', S({ lv: LS([0.05, 0.1, 0.15], [0.15, 0.25, 0.4]) }));
run('продажа +40/60/100: 5/10/15', S({ lv: LS([0.05, 0.1, 0.15], [0.4, 0.6, 1.0]) }));
console.log('— B: фильтры режима (10/20/30) —');
for (const [nm, cond] of [['стратегия продавала ≤ 30 дн назад', I('sold30', '>', 0.5)], ['эйфория в стейблах: usdt < 0,9', I('usdt', '<', 0.9)], ['жадность fng > 70', I('fng', '>', 70)],
  ['монета > 1,5 своей 200д', I('sma200', '>', 1.5)], ['монета > 2 своей 200д', I('sma200', '>', 2)], ['только альты и мемы', I('isbig', '<', 0.5)], ['только мемы', I('meme', '>', 0.5)],
  ['только альты', I('isalt', '>', 0.5)], ['только крупные', I('isbig', '>', 0.5)]]) {
  run(`режим: ${nm}`, S({ cond }));
  run(`   контроль по закрытию`, S({ cond, mode: 'close' }));
}
console.log('— C: переработка позиции: после продажи — лимитка на откуп ниже цены продажи, на всю выручку, 30 дней —');
for (const dd of [0.1, 0.2, 0.3]) run(`продажа 10/20/30 + откуп −${dd * 100}%`, S({ rebuy: { d: dd, f: 1, days: 30 } }));
run('продажа 10/20/30 + откуп −20%, 90 дней', S({ rebuy: { d: 0.2, f: 1, days: 90 } }));
console.log('— D: вместе с покупочной ловушкой (к финалисту) —');
for (const [nm, o] of [['5/10/15', { lv: LS([0.05, 0.1, 0.15]) }], ['10/20/30', {}], ['10/20/30, режим «стратегия продавала»', { cond: I('sold30', '>', 0.5) }], ['10/20/30, только альты', { cond: I('isalt', '>', 0.5) }],
  ['10/20/30 + откуп −20%', { rebuy: { d: 0.2, f: 1, days: 30 } }], ['5/10/15, монета > 2 своей 200д', { lv: LS([0.05, 0.1, 0.15]), cond: I('sma200', '>', 2) }]])
  run(`покупки + продажа ${nm}`, S(o, true), fin);
