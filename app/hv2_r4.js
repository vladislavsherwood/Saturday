/* hv2, круг 4: выигрыш по эпохам. Правила включены только в одной эпохе / во всех, кроме одной (по дню решения).
   Эпохи: бык ≤ 2017, медведь 2018, подъём 2019–21, медведь 2022, подъём 2023–25, медведь 2025–26. Конфигурации: hv; рампа 100–140 × U 250 / 300 × доля 2 / 1,5. */
const X = require('./hv2_lib.js'), { H } = X;
const C = { 'hv (двоично T120, U200, ×2)': {}, 'рампа 100–140, U250, ×2': { gf: X.ramp(100, 140), U: 250 }, 'рампа 100–140, U250, ×1,5': { gf: X.ramp(100, 140), U: 250, M: 1.5 },
  'рампа 100–140, U300, ×2': { gf: X.ramp(100, 140), U: 300 }, 'рампа 100–140, U300, ×1,5': { gf: X.ramp(100, 140), U: 300, M: 1.5 } };
for (const [nm, o] of Object.entries(C)) {
  const r = X.run(nm, o, { quiet: true });
  console.log(`${nm}: доход ${H.sg(r.all)} ${r.ok ? '✔' : '✗'} БД81 ${H.sg(r.hv81.m, 4)} БД100н ${H.sg(r.nhv.m, 4)} 81 ${H.sg(r.m81.m, 4)} 100н ${H.sg(r.n.m, 4)}`);
  X.epochs(nm, o);
}
