/* hv, круг 5: ловушка для фитилей шире / крупнее у волатильной монеты. Уровни — функцией дня выставления (pol.wick.lv(X, jj), есть в стенде с wk):
   если hvv > T на день выставления и монета не крупная — свои уровни; иначе −25/−40/−60 → 15/25/35. */
const H = require('./hv_lib.js');
const LV0 = H.WICK.lv;
const pw = (T, lv) => ({ ...H.polW, wick: { ...H.WICK, lv: (X, jj) => (X.ind.hvv[jj] > T && !(X.ind.isbig[jj] > 0.5) ? lv : LV0) } });
const V = {
  'глубже −30/−50/−70': [[0.3, 0.15], [0.5, 0.25], [0.7, 0.35]],
  'глубже −35/−55/−75': [[0.35, 0.15], [0.55, 0.25], [0.75, 0.35]],
  '+4-й уровень −75% → 20%': [...LV0, [0.75, 0.2]],
  '+4-й уровень −80% → 25%': [...LV0, [0.8, 0.25]],
  'доли ×1,33 (20/33/47)': [[0.25, 0.2], [0.4, 0.33], [0.6, 0.47]],
  'мельче −20/−35/−55': [[0.2, 0.15], [0.35, 0.25], [0.55, 0.35]],
  '−30/−50/−70 → 20/30/40': [[0.3, 0.2], [0.5, 0.3], [0.7, 0.4]],
};
H.head();
H.ev('combo5', H.S5);
for (const [nm, lv] of Object.entries(V)) H.ev(`T115 фитили: ${nm}`, H.S5, pw(115, lv));
for (const T of [100, 130]) for (const nm of ['глубже −30/−50/−70', '+4-й уровень −75% → 20%']) H.ev(`T${T} фитили: ${nm}`, H.S5, pw(T, V[nm]));
